#!/usr/bin/env bash
# A fleet of fake GPU nodes, with KWOK.
#
# KWOK (kubernetes-sigs/kwok) keeps Node objects Ready and "runs" the pods
# scheduled onto them, with no kubelet and no containers. The nodes here get
# their GPUs from their status (the device-plugin path: nvidia.com/gpu) or
# from hand-written ResourceSlices (the DRA path: gpu.nvidia.com), and the
# real scheduler allocates them -- so the plugin sees 6 × 8 H100s, a MIG
# node, L4 and time-sliced T4 nodes, a lost GPU, claims, and pending pods,
# on a laptop.
#
#   dev/kwok-fleet.sh          install KWOK and the fleet into kind cluster $CLUSTER
#   dev/kwok-fleet.sh delete   remove the fleet (the cluster stays)
#
# It uses the kind cluster dev/kind-dra.sh makes (gpu-dra), and creates a
# plain one of that name if there is none -- run kind-dra.sh first for both
# the simulated DRA driver and the fleet in one cluster. Needs kind, kubectl,
# and node (the fleet is generated by dev/kwok/fleet.mjs).
#
# Every kubectl names the kind context explicitly; nothing here touches any
# other cluster.

set -euo pipefail

CLUSTER="${CLUSTER:-gpu-dra}"
NODE_IMAGE="${NODE_IMAGE:-kindest/node:v1.37.0}"
KWOK_VERSION="${KWOK_VERSION:-v0.8.0}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CTX="kind-$CLUSTER"
K=(kubectl --context "$CTX")

say() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
need() { command -v "$1" >/dev/null 2>&1 || { echo "needs $1 on the PATH" >&2; exit 1; }; }
for tool in kind kubectl node; do need "$tool"; done

if [[ "${1:-}" == "delete" ]]; then
    "${K[@]}" delete namespace gpu-fleet --ignore-not-found --wait=false
    "${K[@]}" delete -f "$HERE/manifests/kwok-fleet.yaml" --ignore-not-found
    exit 0
fi

if ! kind get clusters 2>/dev/null | grep -qx "$CLUSTER"; then
    say "creating kind cluster $CLUSTER ($NODE_IMAGE)"
    kind create cluster --name "$CLUSTER" --image "$NODE_IMAGE" --wait 2m
fi

say "installing KWOK $KWOK_VERSION"
# The two manifests KWOK's "kwok in cluster" guide applies: the controller, and
# the stages that make fake nodes Ready and fake pods Running.
"${K[@]}" apply -f "https://github.com/kubernetes-sigs/kwok/releases/download/${KWOK_VERSION}/kwok.yaml"
"${K[@]}" apply -f "https://github.com/kubernetes-sigs/kwok/releases/download/${KWOK_VERSION}/stage-fast.yaml"
"${K[@]}" -n kube-system rollout status deployment/kwok-controller --timeout 3m

say "creating the fleet"
# One pass, in file order: nodes, device classes, ResourceSlices, then the
# namespace and its workloads. The scheduler retries a pod when a slice
# appears, so the order within a second does not matter.
"${K[@]}" apply -f "$HERE/manifests/kwok-fleet.yaml"
# A Node's status is a subresource: `apply` writes it on create and ignores it
# after. Patch it, so the GPUs are right on a second run too.
node "$HERE/kwok/fleet.mjs" status | while read -r name patch; do
    "${K[@]}" patch node "$name" --subresource=status --type=merge -p "$patch" >/dev/null
done

say "waiting for the pods that can run"
sleep 5
"${K[@]}" -n gpu-fleet get pods -o wide
"${K[@]}" get nodes -l type=kwok
cat <<DONE

Done. In K8s Dockside, open the context "$CTX" and the GPU & Accelerators
plugin. Expect 48 H100s (two nodes full with training, five single-GPU pods,
one GPU shared by vllm-a and vllm-b), an A100 node with MIG notebooks, L4s
through the device plugin with one lost on l4-node-2, time-sliced T4s,
llama-finetune waiting for 4 L4s, and too-big-to-fit asking for 16 H100s.

Remove the fleet:  dev/kwok-fleet.sh delete
DONE
